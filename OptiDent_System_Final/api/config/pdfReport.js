/**
 * OptiDent PDF report renderer (pdfkit — free, open source, already a dependency).
 * Every page gets the clinic header and a footer with who generated it, when, and "Page X of Y".
 */
import PDFDocument from 'pdfkit';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const LOGO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../public/assets/lightmode_dentassist.png');
const TEAL = '#0eb1b1', INK = '#0f172a', DIM = '#64748b', RULE = '#e2e8f0', ZEBRA = '#f8fafc';
const MARGIN = 36, HEADER_H = 64, FOOTER_H = 30;

// The built-in PDF fonts only cover Latin-1 + common punctuation: map the peso sign, drop what can't print
const clean = v => String(v ?? '')
    .replace(/₱/g, 'PHP ')
    .replace(/[\r\n\t]+/g, ' ')
    .replace(/[^\x20-\x7E\xA0-\xFF–—‘’“”•…]/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim();

const esc = v => String(v ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const TOOTH_SVG = '<svg width="26" height="26" viewBox="0 0 24 24" fill="none" stroke="#0eb1b1" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M7 3c-2.2 0-4 1.8-4 4.2 0 3.3 1.2 5.3 2 8.3.6 2.3 1 5.5 2.6 5.5 1.7 0 1.6-4.5 4.4-4.5s2.7 4.5 4.4 4.5c1.6 0 2-3.2 2.6-5.5.8-3 2-5 2-8.3C21 4.8 19.2 3 17 3c-2 0-3 1.2-5 1.2S9 3 7 3z"/><path d="M9.5 10.5l2 2 3.5-4"/></svg>';

/** The same report as HTML for the PDF Report API (PDFShift): page body plus repeating header/footer. */
export function buildReportHtml(r) {
    const generatedAt = new Intl.DateTimeFormat('en-PH', { timeZone: 'Asia/Manila', dateStyle: 'long', timeStyle: 'short' }).format(new Date());
    const font = "font-family: -apple-system, 'Segoe UI', Roboto, Arial, sans-serif;";
    const header = `<div style="${font} width:100%; padding:0 36px; box-sizing:border-box; font-size:9px;">
        <div style="display:flex; align-items:center; justify-content:space-between; border-bottom:1.5px solid #0eb1b1; padding:10px 0 8px;">
            <div style="display:flex; align-items:center; gap:8px;">${TOOTH_SVG}
                <div><div style="font-size:14px; font-weight:800; color:#0eb1b1;">OptiDent</div><div style="color:#64748b;">${esc(r.clinicName)}</div></div></div>
            <div style="text-align:right;"><div style="font-weight:700; color:#0f172a;">${esc(r.title)}</div><div style="color:#64748b;">${esc(generatedAt)}</div></div>
        </div></div>`;
    const footer = `<div style="${font} width:100%; padding:0 36px; box-sizing:border-box; font-size:8px; color:#64748b;">
        <div style="display:flex; justify-content:space-between; border-top:0.5px solid #e2e8f0; padding-top:6px;">
            <span>Generated by ${esc(r.generatedBy)} on ${esc(generatedAt)}</span>
            <span>Confidential: contains patient information</span>
            <span>Page {{page}} of {{total}}</span>
        </div></div>`;
    const html = `<!doctype html><html><head><meta charset="utf-8"><style>
        body { ${font} color:#0f172a; margin:0; font-size:10px; }
        h1 { font-size:18px; margin:0 0 2px; } .sub { color:#64748b; font-size:10.5px; }
        .filters { color:#64748b; margin-top:8px; } .filters b { color:#0f172a; font-weight:600; }
        .summary { background:#f0fdfa; border-radius:8px; padding:9px 12px; margin-top:10px; font-weight:700; }
        table { width:100%; border-collapse:collapse; margin-top:14px; }
        thead { display:table-header-group; } tr { page-break-inside:avoid; }
        th { background:#ecfeff; text-align:left; font-size:8.5px; text-transform:uppercase; letter-spacing:.3px; padding:7px 6px; border-bottom:1.5px solid #0eb1b1; }
        td { padding:6px; border-bottom:0.5px solid #e2e8f0; vertical-align:top; }
        tbody tr:nth-child(even) td { background:#f8fafc; }
        .empty { text-align:center; color:#64748b; font-style:italic; padding:18px; }
    </style></head><body>
        <h1>${esc(r.title)}</h1>
        ${r.subtitle ? `<div class="sub">${esc(r.subtitle)}</div>` : ''}
        ${r.filters && r.filters.length ? `<div class="filters">${r.filters.map(([k, v]) => `${esc(k)}: <b>${esc(v)}</b>`).join(' &nbsp;&nbsp; ')}</div>` : ''}
        ${r.summary && r.summary.length ? `<div class="summary">${r.summary.map(esc).join(' &nbsp;|&nbsp; ')}</div>` : ''}
        <table><thead><tr>${r.columns.map(c => `<th>${esc(c)}</th>`).join('')}</tr></thead>
        <tbody>${r.rows.length ? r.rows.map(row => `<tr>${r.columns.map((_, i) => `<td>${esc(row[i])}</td>`).join('')}</tr>`).join('')
            : `<tr><td class="empty" colspan="${r.columns.length}">No records match the selected filters.</td></tr>`}</tbody></table>
    </body></html>`;
    return { html, header, footer, landscape: r.columns.length > 5 };
}

/**
 * Built-in fallback renderer (pdfkit), used when the PDF Report API is unreachable.
 * @param {import('stream').Writable} out  e.g. the Express response
 * @param {{ clinicName: string, title: string, subtitle?: string, filters?: string[][],
 *           summary?: string[], columns: string[], rows: string[][], generatedBy: string }} r
 */
export function renderReportPdf(out, r) {
    const landscape = r.columns.length > 5;
    const doc = new PDFDocument({ size: 'A4', layout: landscape ? 'landscape' : 'portrait', margin: MARGIN, bufferPages: true, info: { Title: clean(r.title), Author: clean(r.clinicName), Creator: 'OptiDent Clinical Management System' } });
    doc.pipe(out);

    const W = doc.page.width - MARGIN * 2;
    const top = MARGIN + HEADER_H;
    const bottom = () => doc.page.height - MARGIN - FOOTER_H;
    const generatedAt = new Intl.DateTimeFormat('en-PH', { timeZone: 'Asia/Manila', dateStyle: 'long', timeStyle: 'short' }).format(new Date());
    const hasLogo = fs.existsSync(LOGO);

    // Column widths: proportional to the longest text in each column (header included), capped
    const sample = r.rows.slice(0, 200);
    const weights = r.columns.map((c, i) => Math.min(Math.max(clean(c).length, ...sample.map(row => clean(row[i]).length), 4), 40));
    const total = weights.reduce((a, b) => a + b, 0);
    const widths = weights.map(w => (w / total) * W);
    const PAD = 5;

    const drawTableHeader = y => {
        doc.rect(MARGIN, y, W, 20).fill('#ecfeff');
        let x = MARGIN;
        doc.font('Helvetica-Bold').fontSize(8.5).fillColor(INK);
        r.columns.forEach((c, i) => { doc.text(clean(c).toUpperCase(), x + PAD, y + 6, { width: widths[i] - PAD * 2, lineBreak: false, ellipsis: true }); x += widths[i]; });
        doc.moveTo(MARGIN, y + 20).lineTo(MARGIN + W, y + 20).lineWidth(1).strokeColor(TEAL).stroke();
        return y + 20;
    };

    // Title block (first page only)
    let y = top;
    doc.font('Helvetica-Bold').fontSize(16).fillColor(INK).text(clean(r.title), MARGIN, y, { width: W });
    y = doc.y + 2;
    if (r.subtitle) { doc.font('Helvetica').fontSize(9.5).fillColor(DIM).text(clean(r.subtitle), MARGIN, y, { width: W }); y = doc.y; }
    if (r.filters && r.filters.length) {
        y += 6;
        doc.font('Helvetica').fontSize(8.5).fillColor(DIM)
            .text(r.filters.map(([k, v]) => `${clean(k)}: ${clean(v)}`).join('     '), MARGIN, y, { width: W });
        y = doc.y;
    }
    if (r.summary && r.summary.length) {
        y += 8;
        const boxTop = y;
        doc.font('Helvetica-Bold').fontSize(9).fillColor(INK);
        const text = r.summary.map(clean).join('     |     ');
        const h = doc.heightOfString(text, { width: W - 20 }) + 14;
        doc.roundedRect(MARGIN, boxTop, W, h, 6).fill('#f0fdfa');
        doc.fillColor(INK).text(text, MARGIN + 10, boxTop + 7, { width: W - 20 });
        y = boxTop + h;
    }
    y = drawTableHeader(y + 12);

    // Rows (wrap long cells, repeat the header row on each new page)
    doc.font('Helvetica').fontSize(8.5);
    r.rows.forEach((row, ri) => {
        const cells = r.columns.map((_, i) => clean(row[i]));
        const h = Math.max(...cells.map((t, i) => doc.heightOfString(t || ' ', { width: widths[i] - PAD * 2 }))) + PAD * 2;
        if (y + h > bottom()) { doc.addPage(); y = drawTableHeader(top); doc.font('Helvetica').fontSize(8.5); }
        if (ri % 2 === 1) doc.rect(MARGIN, y, W, h).fill(ZEBRA);
        let x = MARGIN;
        doc.fillColor(INK);
        cells.forEach((t, i) => { doc.text(t, x + PAD, y + PAD, { width: widths[i] - PAD * 2 }); x += widths[i]; });
        doc.moveTo(MARGIN, y + h).lineTo(MARGIN + W, y + h).lineWidth(0.5).strokeColor(RULE).stroke();
        y += h;
    });
    if (!r.rows.length) doc.font('Helvetica-Oblique').fontSize(10).fillColor(DIM).text('No records match the selected filters.', MARGIN, y + 14, { width: W, align: 'center' });

    // Header + footer on every page, now that the page count is known
    const range = doc.bufferedPageRange();
    for (let i = 0; i < range.count; i++) {
        doc.switchToPage(range.start + i);
        // Footer sits inside the bottom margin; without this pdfkit would start a new page for each footer line
        doc.page.margins.bottom = 0;
        // header
        if (hasLogo) doc.image(LOGO, MARGIN, MARGIN, { height: 34 });
        const tx = MARGIN + (hasLogo ? 42 : 0);
        doc.font('Helvetica-Bold').fontSize(14).fillColor(TEAL).text('OptiDent', tx, MARGIN + 2, { lineBreak: false });
        doc.font('Helvetica').fontSize(8.5).fillColor(DIM).text(clean(r.clinicName), tx, MARGIN + 20, { width: W / 2, lineBreak: false, ellipsis: true });
        doc.font('Helvetica-Bold').fontSize(9).fillColor(INK).text(clean(r.title), MARGIN + W / 2, MARGIN + 4, { width: W / 2, align: 'right', lineBreak: false, ellipsis: true });
        doc.font('Helvetica').fontSize(8).fillColor(DIM).text(generatedAt, MARGIN + W / 2, MARGIN + 18, { width: W / 2, align: 'right', lineBreak: false });
        doc.moveTo(MARGIN, MARGIN + 44).lineTo(MARGIN + W, MARGIN + 44).lineWidth(1.5).strokeColor(TEAL).stroke();
        // footer
        const fy = doc.page.height - MARGIN - 14;
        doc.moveTo(MARGIN, fy - 6).lineTo(MARGIN + W, fy - 6).lineWidth(0.5).strokeColor(RULE).stroke();
        doc.font('Helvetica').fontSize(7.5).fillColor(DIM);
        doc.text(`Generated by ${clean(r.generatedBy)} on ${generatedAt}`, MARGIN, fy, { width: W / 2.4, lineBreak: false, ellipsis: true });
        doc.text('Confidential: contains patient information', MARGIN + W / 2.4, fy, { width: W - (W / 2.4) * 2, align: 'center', lineBreak: false });
        doc.text(`Page ${i + 1} of ${range.count}`, MARGIN + W - W / 2.4, fy, { width: W / 2.4, align: 'right', lineBreak: false });
    }
    doc.end();
}
